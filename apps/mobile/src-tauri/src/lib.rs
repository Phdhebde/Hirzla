//! `hirzla-mobile` — the Android application (ADR 0080 § 8), interface process.
//!
//! A client of the core, like the desktop application (ADR 0007, `docs/api-locale.md`): it
//! holds no key. The cores run apart, one process per vault (`apps/mobile/core`, ADR 0085
//! step 5); this process reaches each over a Unix socket of the application's private
//! directory. The web
//! view talks only to this process, through the commands of [`commands`], under a strict
//! content security policy, with no network access (ADR 0024).
//!
//! - [`link`]: a connection to one core;
//! - [`vaults`]: the vaults of the phone, the core of each in its own slot (ADR 0085);
//! - [`native`]: the Kotlin layer (`HirzlaPlugin`): private directory, `BiometricPrompt`,
//!   sensitive clipboard; never reachable from the web view;
//! - [`commands`]: what the web view may ask, checked strictly;
//! - [`error`]: refusals, in French, without detail useful to an attacker.

#![deny(unsafe_code)]

pub mod commands;
pub mod error;
pub mod link;
pub mod native;
pub mod vaults;

/// Whether the web view may show `url`: only the application's own pages, served by Tauri
/// (`http(s)://tauri.localhost` on Android, `tauri://localhost` elsewhere).
#[must_use]
pub fn is_app_url(url: &tauri::Url) -> bool {
    match url.scheme() {
        "tauri" => url.host_str() == Some("localhost"),
        "http" | "https" => url.host_str() == Some("tauri.localhost") && url.port().is_none(),
        _ => false,
    }
}

/// Refuses any navigation away from the application's pages.
fn navigation_guard<R: tauri::Runtime>() -> tauri::plugin::TauriPlugin<R> {
    tauri::plugin::Builder::new("navigation-guard")
        .on_navigation(|_, url| is_app_url(url))
        .build()
}

/// Builds and runs the application.
///
/// # Errors
/// A failure of the web view.
pub fn run() -> Result<(), tauri::Error> {
    tauri::Builder::default()
        .plugin(navigation_guard())
        .plugin(native::plugin())
        .manage(commands::AppState::default())
        .invoke_handler(tauri::generate_handler![
            commands::app_status,
            commands::list_vaults,
            commands::select_vault,
            commands::lock_all,
            commands::create_vault,
            commands::unlock,
            commands::unlock_fingerprint,
            commands::enroll_fingerprint,
            commands::lock,
            commands::list_secrets,
            commands::reveal_field,
            commands::copy_field,
            commands::create_login,
            commands::enrol_start,
            commands::enrol_wait,
            commands::enrol_finish,
            commands::enrol_cancel,
            commands::server_sync,
            commands::autofill_request,
            commands::autofill_fill,
            commands::autofill_cancel,
            commands::autofill_state,
            commands::autofill_settings,
        ])
        .run(tauri::generate_context!())
}

/// **The second exception to rule 6 of `CLAUDE.md`** (ADR 0080, validation decision 7). On
/// Android, `#[tauri::mobile_entry_point]` expands the JNI glue of Tauri, wry and tao
/// (exported `extern` functions, `unsafe` blocks): code of those crates, not written here,
/// that must be compiled into this library for the JVM to find it. This module holds that
/// entry point and nothing else; `hirzla-keystore/tests/unsafe_policy.rs` checks it.
#[cfg(target_os = "android")]
// SAFETY: the code allowed here is generated by `tauri::mobile_entry_point` (tauri-macros)
// and the `android_binding!` macros of Tauri, wry and tao, at the versions of Cargo.lock;
// this module writes no `unsafe` of its own.
#[allow(unsafe_code)]
mod entry {
    #[tauri::mobile_entry_point]
    fn main() {
        if let Err(e) = super::run() {
            // No secret here: a failure of the web view.
            eprintln!("hirzla: {e}");
        }
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]
    use super::*;

    #[test]
    fn only_the_application_pages_may_be_shown() {
        for ok in ["http://tauri.localhost/index.html", "tauri://localhost/"] {
            assert!(is_app_url(&ok.parse().unwrap()), "{ok}");
        }
        for bad in [
            "https://example.com/",
            "http://tauri.localhost.example.com/",
            "http://tauri.localhost:8080/",
            "file:///data/index.html",
            "data:text/html,x",
        ] {
            assert!(!is_app_url(&bad.parse().unwrap()), "{bad}");
        }
    }
}
